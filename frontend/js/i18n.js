let currentLang = localStorage.getItem('sc360_lang') || 'en';

function t(key) {
  if (translations[currentLang] && translations[currentLang][key]) {
    return translations[currentLang][key];
  }
  return translations['en'][key] || key;
}

function setLanguage(lang) {
  if (!translations[lang]) lang = 'en';
  currentLang = lang;
  localStorage.setItem('sc360_lang', lang);

  // Update HTML lang attribute
  document.documentElement.lang = lang;

  // Translate all DOM elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    el.textContent = t(key);
  });

  // Translate placeholders with data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    el.placeholder = t(key);
  });

  // Update language select dropdown value if present
  document.querySelectorAll('.lang-select').forEach(select => {
    select.value = lang;
  });

  // Dispatch custom event for page scripts
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
}

function initLanguage() {
  document.addEventListener('DOMContentLoaded', () => {
    const saved = localStorage.getItem('sc360_lang') || 'en';
    setLanguage(saved);

    // Attach listener to any .lang-select on page
    document.querySelectorAll('.lang-select').forEach(sel => {
      sel.value = saved;
      sel.addEventListener('change', (e) => {
        setLanguage(e.target.value);
      });
    });
  });
}

// Auto-initialize
initLanguage();

window.i18n = { t, setLanguage, getLang: () => currentLang, translations };
